#!/usr/bin/env python3
"""Regenerate plotterlens-core.js from a PlotterLens checkout.

Haunted Points draws with the same filters as PlotterLens, so rather than
keeping a copy by hand this lifts the generator code out of PlotterLens's
index.html, verbatim, and wraps it in one script exposing PlotterLensCore.

    python tools/sync_plotterlens.py [path/to/plotterLens/index.html]

The default source is the sibling checkout ../terrapen-camera-plot. Sections
are found by marker text, so ordinary edits upstream don't need changes here;
if a marker disappears the script stops and names it.
"""
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SRC = ROOT.parent / "terrapen-camera-plot" / "index.html"
OUT = ROOT / "plotterlens-core.js"


def find(lines, marker, start=0):
    for i in range(start, len(lines)):
        if lines[i].strip().startswith(marker):
            return i
    sys.exit(f"marker not found in PlotterLens source: {marker!r}")


def line(lines, marker):
    return [lines[find(lines, marker)]]


def block(lines, first, last, include_last=True):
    a = find(lines, first)
    b = find(lines, last, a + 1)
    return lines[a : b + 1 if include_last else b]


WRAP_HEAD = """\
  "use strict";
  const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
  // PlotterLens reads these from its camera pipeline; here they are set per run.
  let gray = null, dark = null, gw = 0, gh = 0;
  let live = false, frozen = false;
"""

WRAP_TAIL = """\
  const S = Object.assign({}, DEFAULTS);
  S.pens = DEFAULTS.pens.slice();
  const generate = (mode) => applyBands(applyJitter(applyClip((GEN[mode] || genWave)(DM), DM)), DM);

  // Styles take their line directions and traced shapes from fields().B, a blurred copy of
  // the tone. A host that knows more than a photo can hand over its own structure field
  // (w*h, 0..1) so lines follow that instead, while the tone still sets how much ink goes down.
  const structure = (shape) => (shape ? { B: boxBlur(boxBlur(shape, gw, gh, 1), gw, gh, 1) } : null);

  // gray: Float32Array w*h, 0 black .. 1 white. d: {W,H,mx,my,dw,dh} in mm.
  // Returns [{layer, pts:[x0,y0,x1,y1,...]}] in mm. settle (ms) lets Loop finish growing.
  function run(g, w, h, d, opts) {
    opts = opts || {};
    gray = g; gw = w; gh = h; DM = d; live = !!opts.live; frozen = false;
    computeDark();
    fieldCache = structure(opts.shape);
    let t0 = performance.now(), out = generate(S.mode);
    if (opts.settle) while (loopAnim && performance.now() - t0 < opts.settle) { loopAnim = false; fieldCache = structure(opts.shape); out = generate(S.mode); }
    return out;
  }
  // The style's own coarse preview of a picture, as the PlotterLens carousel draws it.
  function thumb(mode, g, w, h, d, shape) {
    const keep = { mode: S.mode, spacing: S.spacing, levels: S.levels };
    let out = [];
    gray = g; gw = w; gh = h; DM = d; live = false; frozen = false;
    computeDark();
    fieldCache = structure(shape);
    try {
      S.mode = mode; S.spacing = keep.spacing * 2.2; S.levels = Math.min(keep.levels, 6);
      thumbRun = true;
      out = generate(mode);
    } catch (e) { out = []; }
    finally { thumbRun = false; S.mode = keep.mode; S.spacing = keep.spacing; S.levels = keep.levels; }
    return out;
  }
  return {
    S, DEFAULTS, SLIDERS, SP, fmt, SIZES, HIDDEN_MODES, CULL_DEF, CULL_TIPS, COLOUR_TIPS,
    run, thumb, penColour, darkPaper, colourName, scaleOf, boxBlur,
    // contour lines of any w*h field, chained into polylines in page mm
    iso: (F, w, h, levels, d) => { DM = d; return isoMulti(F, w, h, levels); },
    loopBusy: () => loopAnim
  };
"""


def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SRC
    lines = src.read_text(encoding="utf-8").split("\n")

    parts = []
    parts += line(lines, "const SIZES =")
    parts += line(lines, "const BRAND_PENS =")
    parts += line(lines, "const DEFAULTS =")
    parts += line(lines, "const HIDDEN_MODES =")
    parts += line(lines, "const scaleOf =")
    parts += block(lines, "const SPACE_NAMES =", "const fmt =")
    parts += line(lines, "const lumOf =")
    parts += line(lines, "const darkPaper =")
    parts += block(lines, "const COLOUR_NAMES =", "const syncPenNames =", include_last=False)
    parts += line(lines, "const penColour =")
    parts += block(lines, "const COLOUR_TIPS =", "};")
    parts += block(lines, "function computeDark()", "// ---------------- generators:", include_last=False)
    parts += block(lines, "// ---------------- generators:", "const GEN =")
    parts += block(lines, "// Colour bands:", "let liveGap =", include_last=False)

    try:
        commit = subprocess.run(["git", "-C", str(src.parent), "rev-parse", "--short", "HEAD"],
                                capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"

    head = ("// GENERATED by tools/sync_plotterlens.py from PlotterLens (terraLens) "
            f"commit {commit}. Do not edit by hand.\n"
            "// Upstream: https://github.com/warderoid-ctrl/plotterLens (MIT, (c) 2026 Edward Ward)\n"
            "self.PlotterLensCoreFactory = () => {   // a factory, so the page can rebuild it inside a worker from its source\n")
    OUT.write_text(head + WRAP_HEAD + "\n".join(parts) + "\n" + WRAP_TAIL + "};\nself.PlotterLensCore = self.PlotterLensCoreFactory();\n", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes) from {commit}")


if __name__ == "__main__":
    main()
